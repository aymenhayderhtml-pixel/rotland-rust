"""Hit reactions and death animation clips (F4 / A14, A16).

Clips:
- hit_front, hit_back, hit_left, hit_right (0.35 s, no loop): snappy directional flinches and recovery
- hit_head (0.4 s, no loop): head snaps back, hand clutches face, recovery
- stagger_back (0.9 s, no loop): two stumble steps backward, low balance catch, upright recovery
- knockdown (1.0 s, no loop): knocked backward, collapses onto back, ends lying flat on floor
- get_up (1.4 s, no loop): rolls from back, props on hand, feet under body, stands upright
- death_forward (1.3 s, no loop): knees buckle, falls face down onto stomach, ends lying flat on floor
- death_back (1.3 s, no loop): collapses backward onto back, ends lying flat on floor
- death_left, death_right (1.3 s, no loop): twist and collapse onto that side, ends lying flat on floor
- downed_idle (2.0 s, loop): lying half on side, propped on one arm, breathing cycle
- downed_crawl (1.4 s, loop): crawling on belly dragging legs, alternating arm pull
- revive_get_up (1.6 s, no loop): from downed propped pose to standing, weak and hurt

Arm X positive swings arm forward; hips loc Y is world up (negative drops body).
Knee flexion (shin rx) is negative (never bend backward).
All clips are in-place.
"""


def _mirror_bone(name):
    if name.endswith("_L"):
        return name[:-2] + "_R"
    if name.endswith("_R"):
        return name[:-2] + "_L"
    return name


def _mirror_entry(entry):
    if isinstance(entry, dict):
        rx, ry, rz = entry["rot"]
        dx, dy, dz = entry["loc"]
        return {"rot": (rx, -ry, -rz), "loc": (-dx, dy, dz)}
    rx, ry, rz = entry
    return (rx, -ry, -rz)


def _mirror_frame(frame):
    return {_mirror_bone(bone): _mirror_entry(val) for bone, val in frame.items()}


def _mirror_clip_no_loop(clip):
    out_frames = {t: _mirror_frame(pose) for t, pose in clip["frames"].items()}
    return {"length": clip["length"], "loop": clip["loop"], "frames": out_frames}


